#!/usr/bin/env bash
# Replays Annex's commits onto the latest upstream main, regenerates the rebrand commit, and
# checks the result. Run by the nightly T3 scheduled task from a clean checkout of `main`.
#
# Exit codes:
#   0  synced: main now sits on the latest upstream, checks passed, pushed to origin
#   1  checks failed on the rebuilt branch (left checked out as annex-sync for inspection)
#   2  a commit conflicted (cherry-pick left in progress on annex-sync for an agent to resolve;
#      after resolving, `git cherry-pick --continue` and re-run with --resume)
#   3  upstream had nothing new
#
# Flags: --resume  continue after a resolved conflict instead of starting over
#        --no-push check only; leave the result on annex-sync
set -euo pipefail
cd "$(dirname "$0")/.."

REBRAND_SUBJECT="chore(annex): rebrand to Annex"
# The git dir, not .git: in a worktree .git is a file.
queue="$(git rev-parse --git-dir)/annex-sync-queue"
resume=false push=true
for arg in "$@"; do
  case "$arg" in
    --resume) resume=true ;;
    --no-push) push=false ;;
    *) echo "unknown flag: $arg" >&2; exit 64 ;;
  esac
done

if [ -s "$HOME/.nvm/nvm.sh" ]; then
  # shellcheck disable=SC1091
  source "$HOME/.nvm/nvm.sh" >/dev/null
  nvm use "$(node -p 'require("./package.json").engines.node')" >/dev/null
fi

git fetch -q upstream main
git fetch -q origin main

if ! $resume; then
  [ -z "$(git status --porcelain)" ] || { echo "working tree is dirty; refusing to sync" >&2; exit 64; }
  if [ "$(git rev-parse origin/main)" != "$(git rev-parse main)" ]; then
    echo "local main differs from origin/main; push or reset it first" >&2; exit 64
  fi
  base=$(git merge-base main upstream/main)
  if [ "$base" = "$(git rev-parse upstream/main)" ]; then
    echo "upstream has nothing new"; exit 3
  fi
  # Annex's own commits, oldest first, minus the generated rebrand commit.
  git rev-list --reverse "$base..main" > "$queue"
  git checkout -q -B annex-sync upstream/main
fi

while read -r commit; do
  [ -n "$commit" ] || continue
  subject=$(git log -1 --format=%s "$commit")
  # Portable across BSD and GNU, unlike sed -i.
  tail -n +2 "$queue" > "$queue.next" && mv "$queue.next" "$queue"
  [ "$subject" = "$REBRAND_SUBJECT" ] && continue
  if ! git cherry-pick --allow-empty "$commit" >/dev/null; then
    # The route tree is generated, so a conflict there alone is settled by generating it again.
    # --continue commits through the pre-commit hook, which a plain cherry-pick never runs.
    if [ "$(git diff --name-only --diff-filter=U)" = "apps/web/src/routeTree.gen.ts" ] &&
      node annex/routes.mjs && git add apps/web/src/routeTree.gen.ts &&
      GIT_EDITOR=true git -c core.hooksPath=/dev/null cherry-pick --continue >/dev/null; then
      continue
    fi
    echo "CONFLICT replaying $commit: $subject" >&2
    git diff --name-only --diff-filter=U >&2
    exit 2
  fi
done < <(cat "$queue")
rm -f "$queue"

./annex/rebrand.sh >/dev/null
git add -A apps assets scripts packages .github README.md AGENTS.md knip.jsonc
git commit -q -n -m "$REBRAND_SUBJECT" -m "Generated by annex/rebrand.sh. Regenerate instead of resolving conflicts." || true

pnpm install --frozen-lockfile --silent

# Runs one package's tests (only the given files, when any) and prints "<file>\t<test>" for each
# failure, with the file relative to the package. A file that fails to load counts as one failure.
failing_tests() {
  local dir=$1 out root
  shift
  out=$(mktemp)
  root="$(cd "$dir" && pwd -P)/"
  (cd "$dir" && pnpm exec vp test run --passWithNoTests --reporter=json --outputFile="$out" "$@" >/dev/null 2>&1) || true
  jq -r --arg root "$root" '.testResults[] | (.name | ltrimstr($root)) as $file
    | [.assertionResults[]? | select(.status == "failed") | .fullName] as $names
    | (if ($names | length) == 0 and .status == "failed" then ["(file failed to run)"] else $names end)[]
    | "\($file)\t\(.)"' "$out" 2>/dev/null | sort -u
  rm -f "$out"
}

# Typecheck everything; test the packages Annex's commits touch (upstream's CI covers the rest).
# Tests that already fail on upstream main are not Annex's to fix, so only new failures count:
# files that fail here are re-run on a clean upstream checkout, which most nights is never needed.
failed=false
pnpm exec vp run typecheck >/dev/null || { echo "typecheck failed" >&2; failed=true; }
touched=$(git diff --name-only upstream/main HEAD | awk -F/ '$1=="apps"||$1=="packages"{print $1"/"$2}' | sort -u)
baseline=.git/annex-baseline
git worktree remove --force "$baseline" 2>/dev/null || true
for dir in $touched; do
  [ -f "$dir/package.json" ] || continue
  fails=$(failing_tests "$dir")
  [ -n "$fails" ] || continue
  if [ ! -d "$baseline" ]; then
    git worktree add -q --detach "$baseline" upstream/main
    (cd "$baseline" && pnpm install --frozen-lockfile --silent --prefer-offline)
  fi
  files=()
  while IFS= read -r f; do files+=("$f"); done < <(cut -f1 <<<"$fails" | sort -u)
  new=$(comm -23 <(echo "$fails") <(failing_tests "$baseline/$dir" "${files[@]}"))
  if [ -n "$new" ]; then
    echo "new test failures in $dir:" >&2
    echo "$new" | sed 's/^/  /' >&2
    failed=true
  fi
done
git worktree remove --force "$baseline" 2>/dev/null || true
$failed && exit 1

if $push; then
  git checkout -q main
  git reset -q --hard annex-sync
  git push -q --force-with-lease=main:"$(git rev-parse origin/main)" origin main
  git branch -q -D annex-sync
  echo "synced main onto upstream $(git rev-parse --short upstream/main)"
else
  echo "checks passed on annex-sync (not pushed)"
fi
